import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const namesModule = await import('@unicode/unicode-15.1.0/Names/index.js');
const unicodeNames = namesModule.default || namesModule;

const readLegacyCodes = async () => {
  const htmlPath = path.join(repoRoot, 'index.html');
  const html = await fs.readFile(htmlPath, 'utf8');
  const codes = new Set();
  const buttonRegex = /<button[^>]*class=['"][^'"]*global_diacritics[^'"]*['"][^>]*>/gi;
  const idRegex = /id=['"]([0-9A-F]{4,6})['"]/i;
  for (const match of html.matchAll(buttonRegex)) {
    const button = match[0];
    const idMatch = button.match(idRegex);
    if (idMatch && idMatch[1]) {
      const hex = idMatch[1].toUpperCase();
      codes.add(parseInt(hex, 16));
    }
  }
  return codes;
};

const addRange = (set, start, end) => {
  for (let cp = start; cp <= end; cp++) {
    set.add(cp);
  }
};

const legacyCodes = await readLegacyCodes();

const codePoints = new Set(legacyCodes);
addRange(codePoints, 0x00A0, 0x00FF); // Latin-1 Supplement
addRange(codePoints, 0x0100, 0x017F); // Latin Extended-A
addRange(codePoints, 0x0370, 0x03FF); // Greek and Coptic
addRange(codePoints, 0x0400, 0x04FF); // Cyrillic
addRange(codePoints, 0xFE20, 0xFE2F); // Combining Half Marks
codePoints.add(0x266D); // Music flat
codePoints.add(0x266F); // Music sharp

const printableCharacters = Array.from(codePoints)
  .sort((a, b) => a - b)
  .map(codePoint => {
    const code = codePoint.toString(16).toUpperCase().padStart(4, '0');
    const name = typeof unicodeNames?.get === 'function' ? unicodeNames.get(codePoint) : undefined;
    if (!name) {
      return null;
    }
    const char = String.fromCodePoint(codePoint);
    const isControl = /\p{C}/u.test(char);
    const isSpaceSeparator = /\p{Zs}/u.test(char);
    if (isControl || (isSpaceSeparator && codePoint !== 0x00A0)) {
      return null;
    }
    return {
      code,
      char,
      name
    };
  })
  .filter(Boolean);

const outputLines = [
  '// Auto-generated by scripts/generate-special-characters.mjs',
  '// Do not edit manually unless you know what you are doing.',
  'export const SPECIAL_CHARACTERS = ' + JSON.stringify(printableCharacters, null, 2) + ';',
  ''
];

const outDir = path.join(repoRoot, 'shared', 'data');
await fs.mkdir(outDir, { recursive: true });
const outPath = path.join(outDir, 'special-characters.js');
await fs.writeFile(outPath, outputLines.join('\n'), 'utf8');

console.log(`Wrote ${printableCharacters.length} characters to ${path.relative(repoRoot, outPath)}`);
